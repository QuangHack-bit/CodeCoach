#!/usr/bin/env python3
"""Compile modular multi-IDE rules from AGENTS.md and skills/*/SKILL.md (CodeCoach v2).

Usage:
    python scripts/sync_rules.py           # write all generated IDE rule files & clean legacy v1 files
    python scripts/sync_rules.py --check   # exit 1 if any generated file is missing/stale or legacy file remains

Targets:
    Cursor (.cursor/rules/):
        00-core-ponytail.mdc
        10-blueprint-md.mdc
        20-debug-evidence.mdc
        30-embedded-robotics.mdc
        31-java-dsa.mdc
    VS Code / GitHub Copilot (.github/):
        copilot-instructions.md
        instructions/blueprint-anatomy.instructions.md
        instructions/embedded-robotics.instructions.md
        instructions/java-dsa.instructions.md
    Gemini CLI / Antigravity IDE:
        GEMINI.md (deduplicated routing companion — avoids double-loading AGENTS.md tokens)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANNER = "<!-- GENERATED by scripts/sync_rules.py from AGENTS.md & skills/. Do not edit by hand. -->\n\n"
LEGACY_FILES = (".cursor/rules/codecoach.mdc",)


def strip_frontmatter(markdown: str) -> str:
    lines = markdown.splitlines()
    if lines and lines[0].strip() == "---":
        for idx in range(1, len(lines)):
            if lines[idx].strip() == "---":
                return "\n".join(lines[idx + 1 :]).lstrip("\n") + "\n"
    return markdown


def extract_section(markdown: str, heading: str) -> str:
    lines = markdown.splitlines()
    start = None
    for idx, line in enumerate(lines):
        if line.strip() == heading:
            start = idx
            break
    if start is None:
        raise ValueError(f"Missing expected section '{heading}'")
    out = [lines[start]]
    for line in lines[start + 1 :]:
        if line.startswith("## ") and line.strip() != heading:
            break
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def cursor_mdc(description: str, body: str, *, always_apply: bool = False, globs: list[str] | None = None) -> str:
    header = ["---", f"description: {description}"]
    if globs:
        glob_str = ", ".join(f'"{g}"' for g in globs)
        header.append(f"globs: [{glob_str}]")
    header.append(f"alwaysApply: {'true' if always_apply else 'false'}")
    header.append("---\n")
    return "\n".join(header) + BANNER + body


def copilot_instruction(apply_to: str, body: str) -> str:
    header = f'---\napplyTo: "{apply_to}"\n---\n'
    return header + BANNER + body


def render_all() -> dict[str, str]:
    agents_body = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    blueprint_body = strip_frontmatter((ROOT / "skills/codecoach-blueprint/SKILL.md").read_text(encoding="utf-8"))
    anatomy_body = strip_frontmatter((ROOT / "skills/codecoach-anatomy/SKILL.md").read_text(encoding="utf-8"))
    debug_body = strip_frontmatter((ROOT / "skills/codecoach-debug/SKILL.md").read_text(encoding="utf-8"))
    domains_raw = strip_frontmatter((ROOT / "skills/codecoach-domains/SKILL.md").read_text(encoding="utf-8"))

    domains_constraints = extract_section(domains_raw, "## Hard constraints")
    pack_a = extract_section(domains_raw, "## Pack A — Algorithms, Java & OOP (`*.java`, DSA)")
    pack_b = extract_section(
        domains_raw, "## Pack B — Embedded Systems, C/C++, CV & Robotics (`*.c`, `*.cpp`, `*.h`, MCU/ROS 2/CV `*.py`)"
    )

    blueprint_and_anatomy = blueprint_body.rstrip() + "\n\n---\n\n" + anatomy_body
    embedded_pack = "# CodeCoach Domain Pack B — Embedded, C/C++, CV & Robotics\n\n" + domains_constraints + "\n" + pack_b
    java_pack = "# CodeCoach Domain Pack A — Java, OOP & DSA\n\n" + domains_constraints + "\n" + pack_a

    gemini_companion = (
        BANNER
        + "# CodeCoach Custom v2 — Gemini CLI & Antigravity Companion\n\n"
        + "To avoid duplicate token injection, **do not duplicate rules here** — `AGENTS.md` is the single source of truth.\n\n"
        + "1. **Core Laws:** Enforce all hard constraints (`H1`–`H6`, including `H4+` mandatory citations or `[UNVERIFIED]`) in `AGENTS.md`.\n"
        + "2. **Cross-Session Memory:** If `.codecoach/learner-profile.md` exists in the workspace, read it at session start (skip `Mastered` basics; probe `Recurring Blind Spots`).\n"
        + "3. **Skill Dispatch (`skills/*/SKILL.md`):**\n"
        + "   - New module/feature -> `skills/codecoach-blueprint/SKILL.md` (`.md` design before source code)\n"
        + "   - Function frame & parameters -> `skills/codecoach-anatomy/SKILL.md` & `skills/codecoach-predict/SKILL.md`\n"
        + "   - Errors/bugs/hardware faults -> `skills/codecoach-debug/SKILL.md` (3 Evidence Gates)\n"
        + "   - Working learner code -> `skills/codecoach-review/SKILL.md`\n"
        + "   - Java/DSA or C/C++/MCU/ROS 2/CV -> `skills/codecoach-domains/SKILL.md`\n"
        + "   - Milestone complete / wrap-up -> `skills/codecoach-recap/SKILL.md` (3-sentence teach-back + profile sync)\n"
    )

    return {
        ".cursor/rules/00-core-ponytail.mdc": cursor_mdc(
            "CodeCoach v2 core laws: Senior Socratic persona, Ponytail scope lock, H1-H6 & H4+ citation gate, /focus /strict /build /source.",
            agents_body,
            always_apply=True,
        ),
        ".cursor/rules/10-blueprint-md.mdc": cursor_mdc(
            "CodeCoach v2 architecture & frame dissection: .md blueprint before code + 3-layer code anatomy & parameter matrix.",
            blueprint_and_anatomy,
            always_apply=True,
        ),
        ".cursor/rules/20-debug-evidence.mdc": cursor_mdc(
            "CodeCoach v2 3-gate evidence debugging & H4+ citation verification. Use whenever diagnosing errors, crashes, wrong outputs, or hardware faults.",
            debug_body,
            always_apply=False,
        ),
        ".cursor/rules/30-embedded-robotics.mdc": cursor_mdc(
            "CodeCoach v2 Domain Pack B: Embedded C/C++, MCU/STM32, SPI/I2C/UART/DMA, ISR safety, Computer Vision & ROS 2.",
            embedded_pack,
            always_apply=False,
            globs=["*.c", "*.cpp", "*.h", "*.hpp", "*.py"],
        ),
        ".cursor/rules/31-java-dsa.mdc": cursor_mdc(
            "CodeCoach v2 Domain Pack A: Java, OOP encapsulation, loop invariants, complexity & DSA edge cases.",
            java_pack,
            always_apply=False,
            globs=["*.java"],
        ),
        ".github/copilot-instructions.md": BANNER + agents_body,
        ".github/instructions/blueprint-anatomy.instructions.md": copilot_instruction("**", blueprint_and_anatomy),
        ".github/instructions/embedded-robotics.instructions.md": copilot_instruction(
            "**/*.c,**/*.cpp,**/*.h,**/*.hpp,**/*.py", embedded_pack
        ),
        ".github/instructions/java-dsa.instructions.md": copilot_instruction("**/*.java", java_pack),
        "GEMINI.md": gemini_companion,
    }


def main():
    check = "--check" in sys.argv
    stale = []

    for legacy in LEGACY_FILES:
        legacy_path = ROOT / legacy
        if legacy_path.exists():
            stale.append(f"{legacy} (legacy v1 file)")
            if not check:
                legacy_path.unlink()

    for rel, content in render_all().items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    if check:
        if stale:
            print("Out of sync with AGENTS.md / skills:", ", ".join(stale))
            print("Run: python scripts/sync_rules.py")
            sys.exit(1)
        print("All multi-IDE rule files are in sync with AGENTS.md & skills/")
    else:
        print("Synced:", ", ".join(stale) if stale else "nothing (already in sync)")


if __name__ == "__main__":
    main()
